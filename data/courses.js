// ---------- Lookups ----------

const categoryColor = Object.fromEntries(CATEGORIES.map((c) => [c.id, c.color]));
for (const c of COURSES) c.color = categoryColor[c.category];

const courseMap = new Map(COURSES.map((c) => [c.id, c]));

export function getCourse(courseId) {
  return courseMap.get(courseId) || null;
}

export function unitNumber(course, unitIndex) {
  return (course.unitStart || 1) + unitIndex;
}

export function unitLabel(course) {
  return course.unitLabel || "Unit";
}

// Flat, ordered list of every topic in a course with its id ("3.2") and unit.
export function listTopics(course) {
  const out = [];
  course.units.forEach((u, ui) => {
    const n = unitNumber(course, ui);
    u.topics.forEach((title, ti) => {
      out.push({ id: `${n}.${ti + 1}`, title, unitIndex: ui, unitNumber: n, unitTitle: u.title });
    });
  });
  return out;
}

export function getTopic(course, topicId) {
  return listTopics(course).find((t) => t.id === topicId) || null;
}

export function countTopics(course) {
  return course.units.reduce((sum, u) => sum + u.topics.length, 0);
}
